#!/usr/bin/env bash

APP_NAME=$1
PORT=$2
APP_ENV=$3
LOG_LEVEL=$4
MONGO_URI=$5
MONGO_DATABASE=$6
MONGO_CONNECT_TIMEOUT=$7
S3_ENDPOINT_URL=$8
